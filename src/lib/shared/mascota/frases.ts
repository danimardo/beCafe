export type ListaFrases = 'registro' | 'saludo';

export const IDS_REGISTRO: readonly string[] = FRASES_REGISTRO.map((frase) => frase.id);
export const IDS_SALUDO: readonly string[] = FRASES_SALUDO.map((frase) => frase.id);

/** Identificadores de una lista: el catálogo con el que el servidor recorre el ciclo (RN-088). */
export function idsDeLista(lista: ListaFrases): readonly string[] {
	return lista === 'registro' ? IDS_REGISTRO : IDS_SALUDO;
}

const POR_ID = new Map([...FRASES_REGISTRO, ...FRASES_SALUDO].map((frase) => [frase.id, frase]));

/** La frase de un identificador, o `undefined` si ya no está en el catálogo. */
export function buscarFrase(id: string): FraseCapsulito | undefined {
	return POR_ID.get(id);
}
